#!/usr/bin/env node

/**
 * ============================================================================
 * ZENVORA LISTINGS IMPORT PIPELINE (scripts/import-listings.mjs)
 * ============================================================================
 * Dependency-free Node.js script.
 * Reads: incoming/listings.csv and images in incoming/images/
 * Emits: public/images/products/<id>-1.jpg, <id>-2.jpg
 * Generates: lib/generated-products.ts
 * ============================================================================
 */

import fs from "fs";
import path from "path";
import { execSync } from "child_process";

const ROOT = process.cwd();
const CSV_PATH = path.join(ROOT, "incoming", "listings.csv");
const INCOMING_IMAGES_DIR = path.join(ROOT, "incoming", "images");
const OUT_IMAGES_DIR = path.join(ROOT, "public", "images", "products");
const TARGET_TS_PATH = path.join(ROOT, "lib", "generated-products.ts");

const NEUTRAL_PLACEHOLDER =
  "data:image/svg+xml;charset=UTF-8,%3Csvg%20xmlns%3D%22http%3A%2F%2Fwww.w3.org%2F2000%2Fsvg%22%20width%3D%22600%22%20height%3D%22800%22%20viewBox%3D%220%200%20600%20800%22%3E%3Crect%20fill%3D%22%23f3efe9%22%20width%3D%22600%22%20height%3D%22800%22%2F%3E%3Ctext%20fill%3D%22%238f857a%22%20font-family%3D%22sans-serif%22%20font-size%3D%2220%22%20font-weight%3D%22500%22%20letter-spacing%3D%224%22%20x%3D%2250%25%22%20y%3D%2250%25%22%20text-anchor%3D%22middle%22%20dominant-baseline%3D%22middle%22%3EZENVORA%3C%2Ftext%3E%3C%2Fsvg%3E";

/**
 * Robust RFC-4180 quote-aware CSV Parser
 */
function parseCSV(text) {
  const rows = [];
  let currentRow = [];
  let currentVal = "";
  let inQuotes = false;

  let i = 0;
  while (i < text.length) {
    const char = text[i];
    const nextChar = text[i + 1];

    if (inQuotes) {
      if (char === '"') {
        if (nextChar === '"') {
          currentVal += '"';
          i += 2;
          continue;
        } else {
          inQuotes = false;
        }
      } else {
        currentVal += char;
      }
    } else {
      if (char === '"') {
        inQuotes = true;
      } else if (char === ",") {
        currentRow.push(currentVal.trim());
        currentVal = "";
      } else if (char === "\r") {
        // Ignore carriage return
      } else if (char === "\n") {
        currentRow.push(currentVal.trim());
        if (currentRow.some((c) => c !== "")) {
          rows.push(currentRow);
        }
        currentRow = [];
        currentVal = "";
      } else {
        currentVal += char;
      }
    }
    i++;
  }

  if (currentVal || currentRow.length > 0) {
    currentRow.push(currentVal.trim());
    if (currentRow.some((c) => c !== "")) {
      rows.push(currentRow);
    }
  }

  return rows;
}

/**
 * Generates an SEO-friendly slug with collision prevention
 */
function createSlug(name, usedSlugs) {
  const base = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

  let slug = base || "item";
  let count = 2;
  while (usedSlugs.has(slug)) {
    slug = `${base}-${count}`;
    count++;
  }

  usedSlugs.add(slug);
  return slug;
}

/**
 * Copies and optionally optimizes an image using macOS sips or fallback copy
 */
function processImage(filename, destFilename) {
  if (!filename) {
    return NEUTRAL_PLACEHOLDER;
  }

  const srcPath = path.join(INCOMING_IMAGES_DIR, filename);
  if (!fs.existsSync(srcPath)) {
    console.warn(`[WARNING] Image not found in incoming/images/: "${filename}". Using neutral placeholder.`);
    return NEUTRAL_PLACEHOLDER;
  }

  const targetPath = path.join(OUT_IMAGES_DIR, destFilename);

  try {
    if (process.platform === "darwin") {
      try {
        execSync(`sips -s format jpeg -Z 1400 "${srcPath}" --out "${targetPath}"`, {
          stdio: "ignore",
        });
      } catch {
        fs.copyFileSync(srcPath, targetPath);
      }
    } else {
      fs.copyFileSync(srcPath, targetPath);
    }

    return `/images/products/${destFilename}`;
  } catch (err) {
    console.warn(`[WARNING] Error copying image "${filename}": ${err.message}. Using placeholder.`);
    return NEUTRAL_PLACEHOLDER;
  }
}

async function run() {
  console.log("=== ZENVORA Listings Importer ===");

  if (!fs.existsSync(CSV_PATH)) {
    console.log(`[INFO] No "${path.relative(ROOT, CSV_PATH)}" file detected.`);
    console.log(`[INFO] To import listings, copy incoming/listings-template.csv to incoming/listings.csv and run again.`);

    // Write empty generated listings file
    const content = `// This file is auto-generated by \`npm run import-listings\`. DO NOT HAND-EDIT.\nimport type { Product } from "./data";\n\nexport const GENERATED_PRODUCTS: Product[] = [];\n`;
    fs.writeFileSync(TARGET_TS_PATH, content, "utf-8");
    console.log(`[OK] Ensured clean baseline in ${path.relative(ROOT, TARGET_TS_PATH)}`);
    return;
  }

  // Ensure output directory exists
  if (!fs.existsSync(OUT_IMAGES_DIR)) {
    fs.mkdirSync(OUT_IMAGES_DIR, { recursive: true });
  }

  const rawCSV = fs.readFileSync(CSV_PATH, "utf-8");
  const rows = parseCSV(rawCSV);

  if (rows.length <= 1) {
    console.log("[INFO] CSV file has no product rows to process.");
    return;
  }

  const header = rows[0].map((h) => h.toLowerCase());
  const expectedCols = [
    "name",
    "category",
    "subcategory",
    "price",
    "compareatprice",
    "description",
    "sizes",
    "image1",
    "image2",
    "featured",
    "isnew",
    "trending",
  ];

  const colIdx = {};
  for (const col of expectedCols) {
    const idx = header.indexOf(col);
    colIdx[col] = idx;
  }

  const usedSlugs = new Set();
  const validProducts = [];
  let skippedCount = 0;

  for (let r = 1; r < rows.length; r++) {
    const row = rows[r];
    const name = row[colIdx.name] || "";
    const categoryRaw = (row[colIdx.category] || "").toLowerCase();
    const subcategory = row[colIdx.subcategory] || "";
    const priceStr = row[colIdx.price] || "";
    const compareAtPriceStr = row[colIdx.compareatprice] || "";
    const description = row[colIdx.description] || "";
    const sizesStr = row[colIdx.sizes] || "";
    const image1 = row[colIdx.image1] || "";
    const image2 = row[colIdx.image2] || image1; // fallback to image1
    const featuredStr = (row[colIdx.featured] || "").toLowerCase();
    const isNewStr = (row[colIdx.isnew] || "").toLowerCase();
    const trendingStr = (row[colIdx.trending] || "").toLowerCase();

    // Validation
    const errors = [];
    if (!name.trim()) errors.push("Missing 'name'");
    if (categoryRaw !== "women" && categoryRaw !== "men") {
      errors.push(`Invalid 'category' "${categoryRaw}". Must be 'women' or 'men'`);
    }
    if (!subcategory.trim()) errors.push("Missing 'subcategory'");
    const price = parseFloat(priceStr.replace(/[^0-9.]/g, ""));
    if (isNaN(price) || price <= 0) {
      errors.push(`Invalid 'price' "${priceStr}"`);
    }
    if (!image1.trim()) errors.push("Missing 'image1'");

    if (errors.length > 0) {
      console.error(`[ERROR] Row ${r + 1} skipped: ${errors.join(", ")}`);
      skippedCount++;
      continue;
    }

    const id = createSlug(name, usedSlugs);
    const compareAtPrice = compareAtPriceStr
      ? parseFloat(compareAtPriceStr.replace(/[^0-9.]/g, ""))
      : undefined;

    const sizes = sizesStr.trim()
      ? sizesStr.split("|").map((s) => s.trim()).filter(Boolean)
      : ["XS", "S", "M", "L", "XL"];

    const img1Url = processImage(image1, `${id}-1.jpg`);
    const img2Url = processImage(image2, `${id}-2.jpg`);

    const product = {
      id,
      name,
      category: categoryRaw,
      subcategory,
      price,
      ...(compareAtPrice ? { compareAtPrice } : {}),
      description: description || `Meticulously crafted ${name.toLowerCase()} designed for modern minimalism.`,
      sizes,
      images: [img1Url, img2Url],
      featured: ["yes", "true", "1"].includes(featuredStr),
      isNew: ["yes", "true", "1"].includes(isNewStr),
      trending: ["yes", "true", "1"].includes(trendingStr),
    };

    validProducts.push(product);
  }

  // Generate lib/generated-products.ts wholesale
  const fileContent = `// This file is auto-generated by \`npm run import-listings\`. DO NOT HAND-EDIT.
import type { Product } from "./data";

export const GENERATED_PRODUCTS: Product[] = ${JSON.stringify(validProducts, null, 2)};
`;

  fs.writeFileSync(TARGET_TS_PATH, fileContent, "utf-8");

  console.log(`[SUCCESS] Imported ${validProducts.length} listings into ${path.relative(ROOT, TARGET_TS_PATH)}`);
  if (skippedCount > 0) {
    console.log(`[INFO] ${skippedCount} invalid row(s) were skipped.`);
  }
}

run().catch((err) => {
  console.error("[FATAL]", err);
  process.exit(1);
});

